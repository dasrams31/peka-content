#!/usr/bin/env python3
"""Post-process the v3 talking character: 3 poses x 2 mouth states.

v3 adds pose variants (base / wave / present) to the v2 talking
character. Each pose was generated by editing the v2 art, so the
character stays the same; this script:

- Flood-fills the connected near-black background (from the corners)
  to transparent, so the grid shows through (same as v2).
- Scales every state to a common height (1600 px) so the six states
  share one coordinate space (v2 raws are 1600x1600 square, the v3
  pose edits are 1200x2032 portrait).
- NORMALIZES size and position: the v2 square raw frames the
  character smaller (bbox height ~1333 px) than the v3 portrait
  edits (~1564 px), and right-shifted. Without this step a pose swap
  mid-reel would visibly jump in size and position. Every state is
  scaled so its alpha-bbox height equals the tallest bbox, then
  translated so every bbox centre lands at the same point of a
  1200x1600 canvas.
- Aligns each pose's open-mouth state onto its closed-mouth state by
  alpha-bbox centre (tiny residual shift), so swapping mouths never
  shifts the body.
- Crops ALL SIX states with the SAME union bounding box, so swapping
  poses mid-reel never jumps the character.
- Saves: piko-anime-{base,wave,present}-{closed,open}.png
  (the v2 files piko-anime-closed/open.png are left untouched).

Also writes a verification composite per state on a dark-grid
background (/tmp/char-v3-check-<pose>-<mouth>.jpg).
"""
import os

from PIL import Image, ImageDraw

BASE = "/home/hatch/workspace/peka-content/reel-v2/assets/character"
TARGET_H = 1600
CANVAS = (1200, 1600)
TARGET_CENTER = (600, 800)
PAD = 16

SRC = {
    ("base", "closed"): "media-generation-piko-anime-closed-0-b782a2cc-fca0-418d-87d8-80e5a2c0b243.png",
    ("base", "open"): "media-generation-piko-anime-open-0-fd7bf59a-9b73-4920-a3a7-5445a342e734.png",
    ("wave", "closed"): "media-generation-piko-anime-wave-closed-0-24a96e32-9149-4076-bb91-d6112ae64c66.png",
    ("wave", "open"): "media-generation-piko-anime-wave-open-0-047f98c0-888a-4b7c-bc50-5ce45c98337a.png",
    ("present", "closed"): "media-generation-piko-anime-present-closed-0-b04d64fe-a115-4b83-b04f-1c63ce059c78.png",
    ("present", "open"): "media-generation-piko-anime-present-open-0-0df5954e-ac3d-414e-a03f-b2e49515b703.png",
}


def to_rgba(path):
    img = Image.open(path).convert("RGB")
    w, h = img.size
    if h != TARGET_H:
        nw = round(w * TARGET_H / h)
        img = img.resize((nw, TARGET_H), Image.LANCZOS)
        w, h = img.size
    print(os.path.basename(path), img.size, img.mode)
    for xy in [(0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1), (w // 2, 0)]:
        print("  corner", xy, img.getpixel(xy))
    mask = img.convert("L").copy()
    ImageDraw.floodfill(mask, (0, 0), 255, thresh=35)
    alpha = mask.point(lambda v: 0 if v == 255 else 255)
    rgba = img.convert("RGBA")
    rgba.putalpha(alpha)
    return rgba


def bbox_of(im):
    return im.getchannel("A").getbbox()


def bbox_center(b):
    return ((b[0] + b[2]) / 2.0, (b[1] + b[3]) / 2.0)


def main():
    states = {}
    for key, fname in SRC.items():
        states[key] = to_rgba(os.path.join(BASE, fname))

    # 1. Normalize size: every bbox height -> tallest bbox height.
    heights = {}
    for key, im in states.items():
        b = bbox_of(im)
        heights[key] = b[3] - b[1]
        print(key, "bbox", b, "h", b[3] - b[1])
    target_h = max(heights.values())
    print("target bbox height:", target_h)
    for key, im in states.items():
        h = heights[key]
        if h != target_h:
            f = target_h / h
            nw, nh = round(im.width * f), round(im.height * f)
            states[key] = im.resize((nw, nh), Image.LANCZOS)
            print(key, "scaled x", round(f, 4), "->", states[key].size)

    # 2. Align every bbox centre onto TARGET_CENTER of a shared canvas.
    for key, im in states.items():
        b = bbox_of(im)
        c = bbox_center(b)
        dx = int(round(TARGET_CENTER[0] - c[0]))
        dy = int(round(TARGET_CENTER[1] - c[1]))
        canvas = Image.new("RGBA", CANVAS, (0, 0, 0, 0))
        canvas.paste(im, (dx, dy))
        states[key] = canvas
        print(key, "placed at offset", (dx, dy), "bbox now", bbox_of(canvas))

    # 3. Union bbox across all six aligned states, then crop.
    boxes = [bbox_of(im) for im in states.values()]
    print("bboxes:", boxes)
    x0 = min(b[0] for b in boxes) - PAD
    y0 = min(b[1] for b in boxes) - PAD
    x1 = max(b[2] for b in boxes) + PAD
    y1 = max(b[3] for b in boxes) + PAD
    box = (max(0, x0), max(0, y0), x1, y1)
    print("union crop box:", box, "size:", (box[2] - box[0], box[3] - box[1]),
          "aspect_ratio h/w:", round((box[3] - box[1]) / (box[2] - box[0]), 4))
    for (pose, mouth), im in states.items():
        cropped = im.crop(box)
        dest = os.path.join(BASE, f"piko-anime-{pose}-{mouth}.png")
        cropped.save(dest)
        print("saved", dest, cropped.size)

    # Verification composites on a dark-grid background.
    grid = Image.new("RGB", (1080, 1920), (10, 10, 16))
    d = ImageDraw.Draw(grid)
    for x in range(0, 1080, 60):
        d.line([(x, 0), (x, 1920)], fill=(28, 28, 36))
    for y in range(0, 1920, 60):
        d.line([(0, y), (1080, y)], fill=(28, 28, 36))
    for (pose, mouth), im in states.items():
        w = 420
        im2 = im.crop(box).resize((w, int((box[3] - box[1]) * w / (box[2] - box[0]))), Image.LANCZOS)
        canvas = grid.copy()
        canvas.paste(im2, (600, 1150), im2)
        canvas.save(f"/tmp/char-v3-check-{pose}-{mouth}.jpg", quality=90)
        print(f"check /tmp/char-v3-check-{pose}-{mouth}.jpg")


main()
